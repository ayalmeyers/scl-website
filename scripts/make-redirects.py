#!/usr/bin/env python3
"""Generate redirect stubs for the old Webflow URLs of scl.us.com.

The old site's paths come from the Oct 23 audit of the live Webflow site
(see LAUNCH-CHECKLIST.md, "Old-URL redirects"). GitHub Pages has no
server-side redirects, so each old path gets a small static page that
sends the visitor on with a meta refresh, a JavaScript location.replace
and a plain link, and carries noindex plus a canonical tag pointing at
the new page so search engines move their ranking across.

GitHub Pages resolves /our-team to our-team.html and /post/x to
post/x.html on its own, so a stub file at that path is all it takes.
Paths a stub file can't catch (a trailing slash on a file path, odd
capitalisation) fall through to 404.html, which carries the same map
and forwards known paths.

Usage (from the repo root):  python3 scripts/make-redirects.py
It rewrites the stub files and the map block inside 404.html. Edit the
REDIRECTS table below, re-run, and commit the result.
"""
import json
import os
import re

SITE = "https://scl.us.com/"

# old path (no leading slash) -> (new page, optional #fragment, page name)
REDIRECTS = [
    ("our-team", "who-we-are.html", "", "Who We Are"),
    ("who-we-are/farhad-motiwalla", "who-we-are.html", "dlg-farhad", "Farhad Motiwalla"),
    ("who-we-are/sarah-jane-campbell", "who-we-are.html", "dlg-sarah-jane", "Sarah-Jane Campbell"),
    ("who-we-are/jeff-penney", "who-we-are.html", "dlg-jeff", "Jeff Penney"),
    ("who-we-are/jim-zarvos", "who-we-are.html", "dlg-jim", "Jim Zarvos"),
    ("who-we-are/megan-broker", "who-we-are.html", "dlg-megan", "Megan Broker"),
    ("who-we-are/neil-johnson", "who-we-are.html", "dlg-neil", "Neil Johnson"),
    ("what-we-do/executive-coaching", "executive-coaching.html", "", "Executive Coaching"),
    ("what-we-do/1-1-coaching", "executive-coaching.html", "", "Executive Coaching"),
    ("what-we-do/group-skills-development", "executive-coaching.html", "", "Executive Coaching"),
    ("what-we-do/leadership-counsel", "leadership-counsel.html", "", "Leadership Counsel"),
    ("what-we-do/strategic-communication-consulting", "strategic-communication-consulting.html", "", "Strategic Communication Consulting"),
    ("contact-us", "contact.html", "", "Contact Us"),
    ("blog", "musings.html", "", "Musings"),
    ("post/managing-virtual-impressions-the-5-cs", "managing-virtual-impressions.html", "", "Managing Virtual Impressions"),
    ("post/great-leadership", "great-leadership.html", "", "Great Leadership"),
    ("post/learn-to-listen", "learn-to-listen.html", "", "Learn to Listen"),
]

# Folders created by the stubs above get an index page too, so /who-we-are/,
# /what-we-do/ and /post/ land somewhere useful instead of a 404.
FOLDER_INDEXES = [
    ("who-we-are/", "who-we-are.html", "Who We Are"),
    ("what-we-do/", "what-we-do.html", "What We Do"),
    ("post/", "musings.html", "Musings"),
]

STUB = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=device-width, initial-scale=1.0" />
<!-- Generated by scripts/make-redirects.py: old Webflow URL /{old}. Edit the script, not this file. -->
<title>{name} — Strategic Communication Lab</title>
<meta name="description" content="This page has moved to {name} on the Strategic Communication Lab site." />
<meta name="robots" content="noindex" />
<link rel="canonical" href="{canonical}" />
<meta http-equiv="refresh" content="0; url={rel}" />
<link rel="icon" href="{up}favicon.ico" sizes="any" />
<script>
(function () {{
  // Resolve from the site root, not this file's folder, so the redirect
  // holds even if the host serves this page at a trailing-slash URL.
  var prefix = "/scl-website/";
  var root = window.location.pathname.indexOf(prefix) === 0 ? prefix : "/";
  window.location.replace(root + {abs_js});
}})();
</script>
</head>
<body>
<p>This page has moved. Continue to <a href="{rel}">{name}</a>.</p>
</body>
</html>
"""


def write_stub(root, old_file, target, frag, name, old_label):
    depth = old_file.count("/")
    up = "../" * depth
    rel = up + target + ("#" + frag if frag else "")
    html = STUB.format(
        old=old_label,
        name=name,
        canonical=SITE + target,
        rel=rel,
        abs_js=json.dumps(target + ("#" + frag if frag else "")),
        up=up,
    )
    path = os.path.join(root, old_file)
    os.makedirs(os.path.dirname(path) or root, exist_ok=True)
    with open(path, "w") as fh:
        fh.write(html)
    return old_file


def main():
    root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    written = []
    for old, target, frag, name in REDIRECTS:
        written.append(write_stub(root, old + ".html", target, frag, name, old))
    for folder, target, name in FOLDER_INDEXES:
        written.append(write_stub(root, folder + "index.html", target, "", name, folder))

    # The same map, for 404.html's fallback (trailing slashes, capitals).
    js_map = {old: target + ("#" + frag if frag else "") for old, target, frag, _ in REDIRECTS}
    for folder, target, _ in FOLDER_INDEXES:
        js_map[folder.rstrip("/")] = target
    page = os.path.join(root, "404.html")
    with open(page) as fh:
        src = fh.read()
    block = "/* REDIRECT-MAP:START (generated by scripts/make-redirects.py) */\n  var OLD_PATHS = " + json.dumps(js_map, indent=4).replace("\n", "\n  ") + ";\n  /* REDIRECT-MAP:END */"
    new, n = re.subn(r"/\* REDIRECT-MAP:START.*?REDIRECT-MAP:END \*/", lambda m: block, src, flags=re.S)
    if n != 1:
        raise SystemExit("404.html is missing the REDIRECT-MAP markers")
    with open(page, "w") as fh:
        fh.write(new)
    print("wrote", len(written), "stubs and the 404.html map")
    for w in written:
        print("  ", w)


if __name__ == "__main__":
    main()
